/**
 * 保存済みの生フィード(export-crawler-logs.mts の出力)から運休事例を切り出し、原因別の統計を data/recovery-stats.json に書く。
 * Usage: npx tsx scripts/data/derive-episodes.ts <crawler_logs.ndjson>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { seriesFromLogs, episodesOfUnit, mergeIncidents, kaplanMeier, CAUSE_LABELS, type CauseKind, type Episode, type DurationSet } from '../../lib/engine/episodes';

function main() {
    const rows = readFileSync(process.argv[2], 'utf8').trim().split('\n').map(l => JSON.parse(l));
    const series = seriesFromLogs(rows);
    const episodes: Episode[] = [];
    for (const [unit, s] of series) episodes.push(...episodesOfUnit(unit, s));
    const incidents = mergeIncidents(episodes);
    const empty = (): DurationSet => ({ resumed: [], censored: [] });
    const all = empty();
    const byCause: Record<string, DurationSet> = {};
    for (const i of incidents) {
        const set = (byCause[i.cause] ??= empty());
        (i.censored ? set.censored : set.resumed).push(i.minutes);
        (i.censored ? all.censored : all.resumed).push(i.minutes);
    }
    const sortSet = (d: DurationSet) => ({ resumed: d.resumed.sort((a, b) => a - b), censored: d.censored.sort((a, b) => a - b) });
    const iso = (t: number) => new Date(t).toISOString();
    const out = {
        generatedAt: new Date().toISOString(),
        note: 'Generated by scripts/data/derive-episodes.ts from crawler_logs. Do not edit by hand. Minutes from first observed disruption until the JR status code cleared.',
        period: { from: iso(Math.min(...incidents.map(i => i.onset))), to: iso(Math.max(...incidents.map(i => i.onset))) },
        counts: { episodes: episodes.length, incidents: incidents.length, censored: incidents.filter(i => i.censored).length },
        all: sortSet(all),
        byCause: Object.fromEntries(Object.entries(byCause).map(([c, d]) => [c, sortSet(d)])),
    };
    writeFileSync('data/recovery-stats.json', JSON.stringify(out) + '\n');
    console.log('episodes', episodes.length, 'incidents', incidents.length, 'censored', out.counts.censored, out.period.from.slice(0, 10), '→', out.period.to.slice(0, 10));
    for (const [c, d] of Object.entries(out.byCause).sort((a, b) => (b[1].resumed.length + b[1].censored.length) - (a[1].resumed.length + a[1].censored.length))) {
        const k = kaplanMeier(d)!;
        console.log(CAUSE_LABELS[c as CauseKind].padEnd(22), 'n', String(k.n).padStart(3), `(打ち切り ${d.censored.length})`, 'p25/50/75', k.p25, k.median, k.p75, '| 30分', k.within.m30, '1h', k.within.h1, '2h', k.within.h2);
    }
    const k60 = kaplanMeier(out.byCause.animal, 60)!;
    console.log('例: 動物・発生から60分経過 → あと', k60.p25, k60.median, k60.p75, '分 n', k60.n);
}
main();
